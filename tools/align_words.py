# Voice-synced word timing: inside each spoken line, words are placed along the VOICED time
# (10 ms energy above the line's noise floor), weighted by word length. Writes a TS module.
# usage: align_words.py voice.wav lines.json out.ts
import json, sys, wave, numpy as np
wav, lines_p, out = sys.argv[1:4]
w = wave.open(wav); sr = w.getframerate()
a = np.frombuffer(w.readframes(w.getnframes()), np.int16).astype(float).reshape(-1, w.getnchannels()).mean(1) / 32768
hop = sr // 100
env = np.array([np.sqrt(np.mean(a[i:i + hop] ** 2)) + 1e-9 for i in range(0, len(a) - hop, hop)])
db = 20 * np.log10(env)
lines = json.load(open(lines_p))
res = []
for t0, t1, text in lines:
    i0, i1 = int(t0 * 100), max(int(t0 * 100) + 2, int(t1 * 100))
    seg = db[i0:i1]
    thr = max(np.percentile(seg, 20) + 6, -42)
    voiced = (seg > thr).astype(float)
    if voiced.sum() < 3: voiced[:] = 1
    cum = np.cumsum(voiced) / voiced.sum()
    words = text.split(" ")
    clean = [x.strip("*") for x in words]
    weights = np.array([len(x) + 1.5 for x in clean]); share = np.concatenate([[0], np.cumsum(weights)[:-1]]) / weights.sum()
    out_w = []
    for x, sh, raw in zip(clean, share, words):
        k = int(np.searchsorted(cum, sh + 1e-6))
        out_w.append({"w": x, "t": round(t0 + k / 100, 3), "hero": raw.startswith("*")})
    res.append({"t0": t0, "t1": t1, "words": out_w})
open(out, "w").write("// generated by tools/align_words.py — voice-synced word times (source timeline)\nexport const LINES: { t0: number; t1: number; words: { w: string; t: number; hero: boolean }[] }[] = " + json.dumps(res) + ";\n")
print(len(res), "lines")
